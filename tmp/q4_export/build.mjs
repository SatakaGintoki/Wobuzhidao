import fs from 'node:fs/promises';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {Workbook,SpreadsheetFile} from '@oai/artifact-tool';

const here=path.dirname(fileURLToPath(import.meta.url));
const root=path.resolve(here,'../..');
const audit=JSON.parse(await fs.readFile(path.join(root,'results/q4_validation.json'),'utf8'));
if(!audit.pass) throw new Error('Q4 numerical validation failed; export stopped.');
const payload=JSON.parse(await fs.readFile(path.join(root,'results/q4_baseline/excel_payload.json'),'utf8'));
const wb=Workbook.create();
const sheet=wb.worksheets.add(payload.sheet);
const matrix=[payload.headers,...payload.rows];
const nr=matrix.length,nc=matrix[0].length;
sheet.getRangeByIndexes(0,0,nr,nc).values=matrix;
const all=sheet.getRangeByIndexes(0,0,nr,nc);
all.format.font={name:'Microsoft YaHei',size:10};
all.format.rowHeight=20;
all.format.columnWidth=11;
all.format.verticalAlignment='center';
sheet.getRangeByIndexes(0,0,nr,1).format.columnWidth=25;
sheet.getRangeByIndexes(1,1,nr-1,nc-1).setNumberFormat('0.0000');
sheet.getRangeByIndexes(1,0,nr-1,1).setNumberFormat('0');
sheet.getRangeByIndexes(nr-1,0,1,1).setNumberFormat('0.00');
const header=sheet.getRangeByIndexes(0,0,1,nc);
header.format.fill='#E7EDF4';
header.format.font={name:'Microsoft YaHei',size:10,bold:true};
header.format.rowHeight=26;
header.format.horizontalAlignment='center';
sheet.getRangeByIndexes(1,0,nr-1,nc).format.horizontalAlignment='right';
sheet.freezePanes.freezeRows(1);
sheet.freezePanes.freezeColumns(1);
sheet.showGridLines=false;
wb.recalculate();
console.log((await wb.inspect({kind:'table',range:'Sheet1!A1:F5',include:'values,formulas',tableMaxRows:5,tableMaxCols:6,maxChars:1800})).ndjson);
console.log((await wb.inspect({kind:'match',searchTerm:'#REF!|#DIV/0!|#VALUE!|#NAME\\?|#NUM!',options:{useRegex:true,maxResults:10},maxChars:1000})).ndjson);
const preview=await wb.render({sheetName:'Sheet1',range:'A1:H12',scale:1.4,format:'png'});
await fs.writeFile(path.join(here,'preview.png'),new Uint8Array(await preview.arrayBuffer()));
const tailPreview=await wb.render({sheetName:'Sheet1',range:`A${nr-7}:W${nr}`,scale:1,format:'png'});
await fs.writeFile(path.join(here,'preview_tail.png'),new Uint8Array(await tailPreview.arrayBuffer()));
const xlsx=await SpreadsheetFile.exportXlsx(wb);
await xlsx.save(path.join(root,'results/result4.xlsx'));
console.log(JSON.stringify({output:'results/result4.xlsx',rows:nr,columns:nc,report_h:payload.report_h}));
